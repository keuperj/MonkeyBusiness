"""Render the installation guide's Markdown subset into the shared Pages shell.

No third-party dependencies. Run after editing INSTALLATION.md or index.html:
python3 scripts/generate-install-page.py
Use --check to fail if the committed HTML is out of date.
"""
import html
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / 'docs'
SOURCE = DOCS / 'INSTALLATION.md'

def inline(text):
    tokens = []
    def protect(value):
        tokens.append(value)
        return f'\x00{len(tokens)-1}\x00'
    text = re.sub(r'`([^`]+)`', lambda m: protect('<code>'+html.escape(m[1])+'</code>'), text)
    def link(match):
        label, url = match.groups()
        if url.endswith('.md'):
            path = (DOCS / url).resolve().relative_to(ROOT).as_posix()
            url = 'https://github.com/keuperj/MonkeyBusiness/blob/HEAD/' + path
        return protect(f'<a href="{html.escape(url, quote=True)}">{html.escape(label)}</a>')
    text = re.sub(r'\[([^\]]+)\]\(([^)]+)\)', link, text)
    text = html.escape(text)
    text = re.sub(r'\*\*(.+?)\*\*', r'<strong>\1</strong>', text)
    return re.sub(r'\x00(\d+)\x00', lambda m: tokens[int(m[1])], text)

lines = SOURCE.read_text().splitlines()
out, contents = [], []
i = 0
while i < len(lines):
    line = lines[i]
    if not line or line.startswith('# ') or line.startswith('[Back to the project]'):
        i += 1
        continue
    if line.startswith('```'):
        language = line[3:]
        code = []
        i += 1
        while i < len(lines) and not lines[i].startswith('```'):
            code.append(lines[i])
            i += 1
        if i == len(lines):
            raise ValueError('Unclosed code block')
        out.append('<pre tabindex="0" aria-label="Command example"><code class="language-'+html.escape(language)+'">'+html.escape('\n'.join(code))+'</code></pre>')
        i += 1
    elif line.startswith('##'):
        match = re.fullmatch(r'(#{2,3}) (.+)', line)
        if not match:
            raise ValueError('Unsupported heading: '+line)
        level, title = len(match[1]), match[2]
        anchor = re.sub(r'[^a-z0-9]+', '-', title.lower()).strip('-')
        out.append(f'<h{level} id="{anchor}">{inline(title)}</h{level}>')
        if level == 2:
            contents.append(f'<a href="#{anchor}">{html.escape(title)}</a>')
        i += 1
    elif line.startswith('- '):
        items = []
        while i < len(lines) and lines[i].startswith('- '):
            items.append('<li>'+inline(lines[i][2:])+'</li>')
            i += 1
        out.append('<ul>'+''.join(items)+'</ul>')
    elif line.startswith('|'):
        rows = []
        while i < len(lines) and lines[i].startswith('|'):
            rows.append([cell.strip() for cell in lines[i].strip('|').split('|')])
            i += 1
        header = ''.join('<th scope="col">'+inline(cell)+'</th>' for cell in rows[0])
        body = ''.join('<tr>'+''.join('<td>'+inline(cell)+'</td>' for cell in row)+'</tr>' for row in rows[2:])
        out.append('<div class="guide-table"><table><thead><tr>'+header+'</tr></thead><tbody>'+body+'</tbody></table></div>')
    else:
        paragraph = []
        while i < len(lines) and lines[i] and not lines[i].startswith(('#', '```', '- ', '|')):
            paragraph.append(lines[i])
            i += 1
        out.append('<p>'+inline(' '.join(paragraph))+'</p>')

landing = (DOCS / 'index.html').read_text()
header = re.search(r'  <header.*?</header>', landing, re.S)[0]
header = header.replace('href="#main"', 'href="index.html"').replace('href="#aboard"', 'href="index.html#aboard"').replace('href="#gallery"', 'href="index.html#gallery"')
header = header.replace('href="install.html"', 'href="install.html" aria-current="page"')
footer = re.search(r'  <footer>.*?</footer>', landing, re.S)[0]
page = '''<!doctype html>
<!-- Generated by scripts/generate-install-page.py; edit INSTALLATION.md instead. -->
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="theme-color" content="#102c30">
  <meta name="description" content="Install and play Monkey Buisness: local setup, Docker hosting, saves, controls and troubleshooting.">
  <title>Install &amp; play — Monkey Buisness</title>
  <link rel="icon" href="assets/favicon.svg" type="image/svg+xml">
  <link rel="stylesheet" href="assets/site.css">
</head>
<body class="installation-page">
  <a class="skip-link" href="#main">Skip to installation guide</a>
'''+header+'''
  <main id="main" class="install-guide">
    <div class="guide-heading">
      <img src="assets/icon-chest.png" width="80" height="80" alt="">
      <p class="eyebrow">Your passage to Brindle Quay</p>
      <h1>Install &amp; play</h1>
      <p class="lede">Choose your berth: run locally with Node.js, or let Docker carry the supplies.</p>
      <p class="small">This guide installs the game; the website itself is not a playable deployment. No account or generation API key required.</p>
      <a href="https://github.com/keuperj/MonkeyBusiness/blob/HEAD/docs/INSTALLATION.md">Read this guide on GitHub</a>
    </div>
    <nav class="guide-toc" aria-label="Installation contents">
      <h2>Chart your course</h2>
'''+ '\n'.join(contents)+'''
    </nav>
    <article class="guide-body" aria-label="Installation instructions">
'''+ '\n'.join(out)+'''
    </article>
    <p class="guide-back"><a class="button secondary" href="index.html">Back to the adventure</a></p>
  </main>
'''+footer+'''
</body>
</html>
'''
target = DOCS / 'install.html'
if '--check' in sys.argv:
    if not target.exists() or target.read_text() != page:
        sys.exit('Installation page is stale. Run python3 scripts/generate-install-page.py')
    print('Installation page matches its Markdown source and landing-page shell.')
else:
    target.write_text(page)
    print('Generated '+str(target))